/*
# Create private Drive storage bucket

## Plain-English summary
Creates a private cloud storage bucket named `drive` where all uploaded school documents are kept.
Every file is stored under a folder named after the student's user id, and access rules ensure
a student can only read, upload, replace or delete files inside their own folder.

## Changes
1. New private bucket `drive` (not publicly readable), with a 50 MB per-file size limit.
2. Four policies on storage objects in `drive` (select, insert, update, delete) for the `authenticated` role,
   each requiring the first path segment to equal the signed-in user's id.

## Important notes
1. Downloads and previews use short-lived signed links generated by the app for the owner only.
2. The statement is idempotent: the bucket insert uses ON CONFLICT, and policies are dropped before re-creation.
*/

INSERT INTO storage.buckets (id, name, public, file_size_limit)
VALUES ('drive', 'drive', false, 52428800)
ON CONFLICT (id) DO UPDATE SET public = false, file_size_limit = 52428800;

DROP POLICY IF EXISTS "drive_select_own_objects" ON storage.objects;
CREATE POLICY "drive_select_own_objects" ON storage.objects FOR SELECT TO authenticated
USING (bucket_id = 'drive' AND (storage.foldername(name))[1] = auth.uid()::text);

DROP POLICY IF EXISTS "drive_insert_own_objects" ON storage.objects;
CREATE POLICY "drive_insert_own_objects" ON storage.objects FOR INSERT TO authenticated
WITH CHECK (bucket_id = 'drive' AND (storage.foldername(name))[1] = auth.uid()::text);

DROP POLICY IF EXISTS "drive_update_own_objects" ON storage.objects;
CREATE POLICY "drive_update_own_objects" ON storage.objects FOR UPDATE TO authenticated
USING (bucket_id = 'drive' AND (storage.foldername(name))[1] = auth.uid()::text)
WITH CHECK (bucket_id = 'drive' AND (storage.foldername(name))[1] = auth.uid()::text);

DROP POLICY IF EXISTS "drive_delete_own_objects" ON storage.objects;
CREATE POLICY "drive_delete_own_objects" ON storage.objects FOR DELETE TO authenticated
USING (bucket_id = 'drive' AND (storage.foldername(name))[1] = auth.uid()::text);
